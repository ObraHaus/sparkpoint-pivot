"use client";

/**
 * 047 — Admin → System → Bots. Is the testnet activity fleet actually running?
 *
 * The bots run OFF the deployed stack, holding their own keys, because the agent is provably
 * keyless and that property is load-bearing (N2). The cost of that separation is that nothing here
 * can see them directly — so the runner reports each run and this panel renders those reports.
 *
 * ⚠️ Read-only, and deliberately so. There is no start, no stop and no cadence control, because
 * adding one would mean the deployed stack could make a bot sign something. The schedule belongs
 * to the runner; this screen shows what the runner said it would do and what it actually did.
 *
 * The states exist because "quiet" has three very different causes and they must not look alike:
 *   never-run  nothing has ever reported     → the fleet was never started here
 *   overdue    it promised to return and didn't → the runner is down
 *   failing    it ran on time and landed nothing → the fleet is up and broken
 * A panel that renders all three as an empty table is how a dead fleet stays unnoticed.
 */

import { useEffect, useState } from "react";
import { APP_CHAIN_ID_HEADER } from "@/lib/chain/appChain";

interface Stream {
  networkId: string;
  command: string;
  state: "healthy" | "overdue" | "failing" | "never-run";
  schedule: string | null;
  lastRunAt: string | null;
  nextRunAt: string | null;
  attempted: number;
  succeeded: number;
  runnerCommit: string | null;
  overdueSeconds?: number;
}
interface RecentRun {
  networkId: string;
  command: string;
  finishedAt: string;
  ok: boolean;
  attempted: number;
  succeeded: number;
}
interface BotsStatus {
  configured: boolean;
  generatedAt?: string;
  streams: Stream[];
  recent: RecentRun[];
}

const NETWORK_LABEL: Record<string, string> = {
  base: "Base Sepolia",
  robinhood: "Robinhood testnet",
};

const STATE_LABEL: Record<Stream["state"], string> = {
  healthy: "Running",
  overdue: "Overdue",
  failing: "Failing",
  "never-run": "Never run",
};

/** Semantic colour, not decoration: `failing` must not read like `overdue`. */
const STATE_PILL: Record<Stream["state"], string> = {
  healthy: "ok",
  overdue: "amber",
  failing: "bad",
  "never-run": "info",
};

/** Humanise a duration in seconds. Pure — no clock read. */
function duration(seconds: number): string {
  const n = Math.abs(Math.round(seconds));
  if (n < 90) return `${n}s`;
  if (n < 5400) return `${Math.round(n / 60)}m`;
  if (n < 172800) return `${Math.round(n / 3600)}h`;
  return `${Math.round(n / 86400)}d`;
}

/**
 * Relative time against a `now` passed IN, never read from the clock.
 *
 * ⚠️ `Date.now()` during render is impure: it makes the server and client markup disagree and
 * trips the purity lint. `now` is state, refreshed on the same tick as the fetch, so every row on
 * screen is also measured against the same instant rather than drifting apart mid-render.
 */
function ago(iso: string | null, now: number): string {
  if (!iso) return "—";
  const ms = new Date(iso).getTime();
  if (!Number.isFinite(ms)) return "—";
  const seconds = Math.round((now - ms) / 1000);
  return seconds < 0 ? `in ${duration(seconds)}` : `${duration(seconds)} ago`;
}

export function BotsPanel() {
  const [data, setData] = useState<BotsStatus | null>(null);
  const [state, setState] = useState<"loading" | "ok" | "error">("loading");
  // The clock as STATE, stamped when data arrives — see `ago`.
  const [now, setNow] = useState(0);

  useEffect(() => {
    let live = true;
    const load = () =>
      fetch("/api/agent/admin/bots/status", { headers: { "x-chain-id": APP_CHAIN_ID_HEADER }, cache: "no-store" })
        .then((r) => (r.ok ? r.json() : Promise.reject(new Error(String(r.status)))))
        .then((d: BotsStatus) => live && (setData(d), setNow(Date.now()), setState("ok")))
        .catch(() => live && setState("error"));
    void load();
    const t = setInterval(load, 30_000);
    return () => {
      live = false;
      clearInterval(t);
    };
  }, []);

  const streams = data?.streams ?? [];
  // The worst state wins the header. An admin glancing at the tab should learn the bad news here.
  const worst: Stream["state"] | null = streams.some((s) => s.state === "failing")
    ? "failing"
    : streams.some((s) => s.state === "overdue")
      ? "overdue"
      : streams.some((s) => s.state === "never-run")
        ? "never-run"
        : streams.length > 0
          ? "healthy"
          : null;

  return (
    <>
      <div className="pghead">
        <div>
          <h1>Activity bots</h1>
          <div className="sub">
            Testnet activity generated by the operator fleet, so the revenue surfaces have something
            to show. The runner holds its own keys and owns its own schedule — this screen is a
            mirror of what it reported, and cannot start or stop anything.
          </div>
        </div>
        <span className={`pill ${state === "loading" ? "info" : worst ? STATE_PILL[worst] : "info"}`}>
          <span className="led" />
          {state === "loading" ? "Checking…" : worst ? STATE_LABEL[worst] : "Not reporting"}
        </span>
      </div>

      {state === "error" && (
        <div className="infobanner" style={{ background: "var(--caution-subtle)" }}>
          Couldn’t load bot status.
        </div>
      )}

      {data && !data.configured && state === "ok" && (
        <div className="infobanner" style={{ background: "var(--caution-subtle)" }}>
          No runner has ever reported to this deployment. The fleet lives in{" "}
          <span className="mono">ops/testnet-bots</span> and reports only when{" "}
          <span className="mono">AGENT_BASE_URL</span> and <span className="mono">AGENT_S2S_TOKEN</span>{" "}
          are set on the machine running it. Nothing is wrong with the app.
        </div>
      )}

      <div className="chartcard">
        <div className="ch">
          <span className="ct">Streams</span>
          {data?.generatedAt && <span className="prov">as of {ago(data.generatedAt, now)}</span>}
        </div>
        <div style={{ overflowX: "auto" }}>
          <table className="tbl" style={{ width: "100%", minWidth: 620 }}>
            <thead>
              <tr>
                <th>Network</th>
                <th>Job</th>
                <th>State</th>
                <th>Last run</th>
                <th>Next run</th>
                <th>Landed</th>
                <th>Schedule</th>
              </tr>
            </thead>
            <tbody>
              {streams.length === 0 ? (
                <tr>
                  <td colSpan={7} className="muted" style={{ padding: "10px 8px", fontSize: 13 }}>
                    {state === "loading" ? "Loading…" : "No streams reported."}
                  </td>
                </tr>
              ) : (
                streams.map((s) => (
                  <tr key={`${s.networkId}:${s.command}`}>
                    <td>{NETWORK_LABEL[s.networkId] ?? s.networkId}</td>
                    <td className="mono">{s.command}</td>
                    <td>
                      <span className={`pill ${STATE_PILL[s.state]}`}>
                        <span className="led" />
                        {STATE_LABEL[s.state]}
                      </span>
                    </td>
                    <td>{ago(s.lastRunAt, now)}</td>
                    <td>
                      {/* An overdue stream shows how late, not a timestamp in the past that the
                          reader has to subtract from the clock themselves. */}
                      {s.state === "overdue" && s.overdueSeconds !== undefined
                        ? `overdue by ${duration(s.overdueSeconds)}`
                        : ago(s.nextRunAt, now)}
                    </td>
                    <td className="mono">
                      {s.state === "never-run" ? "—" : `${s.succeeded}/${s.attempted}`}
                    </td>
                    <td className="muted">{s.schedule ?? "—"}</td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>
      </div>

      <div className="chartcard">
        <div className="ch">
          <span className="ct">Recent runs</span>
        </div>
        <div style={{ overflowX: "auto" }}>
          <table className="tbl" style={{ width: "100%", minWidth: 520 }}>
            <thead>
              <tr>
                <th>Finished</th>
                <th>Network</th>
                <th>Job</th>
                <th>Landed</th>
              </tr>
            </thead>
            <tbody>
              {(data?.recent ?? []).length === 0 ? (
                <tr>
                  <td colSpan={4} className="muted" style={{ padding: "10px 8px", fontSize: 13 }}>
                    {state === "loading" ? "Loading…" : "Nothing reported yet."}
                  </td>
                </tr>
              ) : (
                (data?.recent ?? []).map((r, i) => (
                  <tr key={i}>
                    <td>{ago(r.finishedAt, now)}</td>
                    <td>{NETWORK_LABEL[r.networkId] ?? r.networkId}</td>
                    <td className="mono">{r.command}</td>
                    <td className="mono">
                      {r.succeeded}/{r.attempted}
                      {r.attempted > 0 && r.succeeded === 0 && (
                        <span className="muted"> · nothing landed</span>
                      )}
                    </td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>
      </div>

      <div className="muted" style={{ fontSize: 12, marginTop: 10, lineHeight: 1.5 }}>
        This activity is ours. It proves the mechanism, not demand — never present it as adoption,
        and never quote these figures as a forecast.
      </div>
    </>
  );
}
