-- =============================================================================
-- 0037_bot_runs.sql  -  Feature 047: what the testnet activity bots actually did
-- =============================================================================
-- 046 added `ops/testnet-bots`, an operator tool that drives real product activity on the testnets
-- so the revenue surfaces have something honest to show. It runs on a schedule, off the deployed
-- stack, holding its own keys — deliberately NOT inside the agent, which is provably keyless and
-- must stay that way (N2).
--
-- That separation leaves one question the panel cannot answer from chain state alone: **is the
-- fleet running?** A quiet chain looks identical whether the bots are healthy and idle between
-- ticks, stopped, or failing on every attempt. Absence is not failure, and it is not health
-- either — so the runner reports each run here and the admin view reads it.
--
-- What this table is NOT: a control plane. Nothing reads it to decide anything, no schedule is
-- stored to be enforced, and no row grants authority. The runner owns its own cadence; these rows
-- are its account of what happened, and `next_run_at` is the runner's own statement of intent —
-- which is exactly why an overdue one is meaningful (the runner said it would be back and was not).
--
-- Additive, idempotent, order-insensitive: no existing surface reads it, so an old agent is
-- unaffected and a new agent on an unapplied DB degrades to `configured:false` on the bot view
-- alone. Apply with PGCLIENTENCODING=UTF8 (the dev DB is SQL_ASCII).
-- =============================================================================

CREATE TABLE IF NOT EXISTS bot_runs (
    id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),

    -- `run_key` is generated by the runner, one per run, so a retried report is a no-op rather
    -- than a duplicate. The runner posts AFTER the work is done, and a network blip on that post
    -- must not be able to inflate the record of what happened.
    run_key        text NOT NULL UNIQUE,

    network_id     text NOT NULL,   -- 'base' | 'robinhood' (the same ids the indexers use)
    command        text NOT NULL,   -- 'accrue' | 'swap' | 'vault' | 'fund'

    started_at     timestamptz NOT NULL,
    finished_at    timestamptz NOT NULL,
    ok             boolean     NOT NULL,

    -- Attempted vs succeeded, kept apart on purpose. A run where every action was refused still
    -- "completed", and reporting that as success is how a fleet that stopped working goes
    -- unnoticed. The admin view derives `failing` from the gap between these two.
    attempted      integer     NOT NULL DEFAULT 0,
    succeeded      integer     NOT NULL DEFAULT 0,

    -- The runner's declared cadence, as a human string ('hourly', '0 * * * *'). Display only.
    schedule       text,
    -- The runner's own statement of when it will next run. NULL for a one-off invocation.
    -- ⚠️ A past value is not a bug in this column: it means the runner did not come back, and the
    -- view is required to render that as overdue rather than as a future promise.
    next_run_at    timestamptz,

    runner_commit  text,           -- which build produced the run
    detail         jsonb       NOT NULL DEFAULT '{}'::jsonb,
    recorded_at    timestamptz NOT NULL DEFAULT now()
);

-- The one query the view makes: newest run per (network, command).
CREATE INDEX IF NOT EXISTS idx_bot_runs_stream
    ON bot_runs (network_id, command, started_at DESC);

-- Retention sweeps and the "recent activity" list both read by time alone.
CREATE INDEX IF NOT EXISTS idx_bot_runs_started
    ON bot_runs (started_at DESC);
