# ruff: noqa: S101
"""Tests for the broker ledger (feature 044).

The theme: **a log is a candidate, the chain is the verdict.** Most of these assert that a stale or
misleading log does not become a wrong answer, because that is the failure this module exists to
prevent — and because every one of those failures is silent. A holder dropped from an allocation
does not raise; they just get nothing.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import pytest
from eth_utils import keccak

from sparkpoint_agent.chain.broker_ledger import (
    SEL_ACTIVATED_AT,
    SEL_OWNER_OF,
    SEL_WEIGHT_OF,
    TOPIC_ACTIVATED,
    TOPIC_TRANSFER,
    ActivatedBroker,
    BrokerLedger,
    from_block_from_env,
)

BROKER = "0x15D269B1f2c9C4b2f8e0a1c3D5e7F9a1B3c5D7f2"
REGISTRY = "0xf081167b0000000000000000000000000000a88E"
ALICE = "0xAaAaAaAa00000000000000000000000000000001"
BOB = "0xBbBbBbBb00000000000000000000000000000002"


def _word(v: int) -> str:
    return f"{v:064x}"


def _addr_topic(a: str) -> str:
    return "0x" + _word(int(a, 16))


def _transfer_log(to: str, token_id: int) -> dict[str, Any]:
    return {
        "topics": [TOPIC_TRANSFER, _addr_topic(ALICE), _addr_topic(to), "0x" + _word(token_id)]
    }


def _activated_log(holder: str, token_id: int) -> dict[str, Any]:
    return {"topics": [TOPIC_ACTIVATED, _addr_topic(holder), "0x" + _word(token_id)]}


class FakeRpc:
    """Scriptable RPC. `owners`/`activated`/`weights` are the CHAIN — the authority."""

    def __init__(
        self,
        *,
        head: int = 1_000,
        transfer_logs: list[dict[str, Any]] | None = None,
        activated_logs: list[dict[str, Any]] | None = None,
        owners: dict[int, str] | None = None,
        activated: dict[int, int] | None = None,
        weights: dict[int, int] | None = None,
        fail_logs: bool = False,
        fail_head: bool = False,
    ) -> None:
        self.head = head
        self.transfer_logs = transfer_logs or []
        self.activated_logs = activated_logs or []
        self.owners = owners or {}
        self.activated = activated or {}
        self.weights = weights or {}
        self.fail_logs = fail_logs
        self.fail_head = fail_head
        self.log_calls: list[dict[str, Any]] = []

    async def call(self, method: str, params: list[Any]) -> Any:
        if method == "eth_blockNumber":
            if self.fail_head:
                raise RuntimeError("node down")
            return hex(self.head)

        if method == "eth_getLogs":
            if self.fail_logs:
                raise RuntimeError("log range rejected")
            spec = params[0]
            self.log_calls.append(spec)
            topics = spec.get("topics") or []
            if topics and topics[0] == TOPIC_TRANSFER:
                wanted = topics[2] if len(topics) > 2 else None
                return [
                    lg
                    for lg in self.transfer_logs
                    if wanted is None or lg["topics"][2].lower() == wanted.lower()
                ]
            return list(self.activated_logs)

        if method == "eth_call":
            data = params[0]["data"]
            selector, arg = data[:10], int(data[10:], 16)
            if selector == SEL_OWNER_OF:
                owner = self.owners.get(arg)
                if owner is None:
                    raise RuntimeError("TokenDoesNotExist")
                return "0x" + _word(int(owner, 16))
            if selector == SEL_ACTIVATED_AT:
                return "0x" + _word(self.activated.get(arg, 0))
            if selector == SEL_WEIGHT_OF:
                return "0x" + _word(self.weights.get(arg, 0))
        raise AssertionError(f"unexpected call {method} {params}")


def _ledger(rpc: FakeRpc, **kw: Any) -> BrokerLedger:
    return BrokerLedger(
        rpc=rpc, broker=BROKER, registries=kw.pop("registries", [REGISTRY]), from_block=0, **kw
    )


# ── the selectors are computed, not trusted ────────────────────────────────────────────────────


def _selector(signature: str) -> str:
    """`keccak256(signature)[:4]` — the selector, derived rather than typed."""
    return "0x" + keccak(text=signature)[:4].hex()


def _topic(signature: str) -> str:
    return "0x" + keccak(text=signature).hex()


def _abi_source(name: str) -> str:
    """The COMMITTED ABI for a contract, generated by `contracts/script/export-abis.sh`.

    Read rather than shelled out to `cast`: foundry is not installed in the agent CI job, and a
    guard that skips in CI is a guard that does not exist. These files are checked in and a CI gate
    asserts they are current, so they are a trustworthy stand-in for the build.
    """
    path = Path(__file__).resolve().parents[4] / "packages" / "shared" / "src" / "abis" / name
    return path.read_text(encoding="utf-8") if path.exists() else ""


def test_selectors_are_derived_from_their_signatures() -> None:
    """Recompute every selector from its signature.

    ⚠️ Two of these were WRONG when first hand-written, and nothing failed: a bad selector makes
    `eth_call` return empty, which degrades to "weight 0", which silently drops that holder from
    the split. There is no error to notice — hence deriving them instead of trusting the constant.
    """
    assert SEL_OWNER_OF == _selector("ownerOf(uint256)")
    assert SEL_ACTIVATED_AT == _selector("activatedAt(uint256)")
    assert SEL_WEIGHT_OF == _selector("weightOf(uint256)")


def test_event_topics_are_derived_from_their_signatures() -> None:
    assert TOPIC_TRANSFER == _topic("Transfer(address,address,uint256)")
    assert TOPIC_ACTIVATED == _topic("Activated(address,uint256,uint8,uint256,uint32)")


def test_the_signatures_themselves_match_the_real_contracts() -> None:
    """Deriving from a signature only helps if the signature is the one the contract actually has.

    A correctly-derived selector for a function that does not exist fails exactly the same silent
    way, so the names and argument counts are checked against the committed ABIs.
    """
    registry = _abi_source("brokerActivationRegistry.ts")
    broker = _abi_source("sparkyBroker.ts")
    if not registry or not broker:  # pragma: no cover - abis absent in a partial checkout
        pytest.skip("committed ABIs not present")

    assert '"name": "weightOf"' in registry or '"weightOf"' in registry
    assert '"activatedAt"' in broker
    assert '"ownerOf"' in broker
    # The event this module scans for. Its argument list is what TOPIC_ACTIVATED encodes, so a
    # changed signature must break the derivation above rather than silently match nothing.
    assert '"Activated"' in registry


