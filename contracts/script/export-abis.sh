#!/usr/bin/env bash
# T015 — ABI export pipeline.
#
# Emits the ABIs of the SparkPoint-owned contracts from the Foundry build
# (`contracts/out/`) into `packages/shared/src/abis/` as typed `as const` TS
# modules, so the frontend (`apps/web/src/lib/chain`) and any TS consumer bind to
# the SAME ABI the deploy uses — no hand-maintained/guessed ABIs, no drift. The
# concrete addresses live in the address registry (R14); this file is ABIs only.
#
# Deterministic: sorted keys via `jq -S`, stable header, no timestamps — so
# re-running is a no-op in git and CI can assert the checked-in ABIs are current
# (see .github/workflows/contracts.yml "abi export up-to-date" gate).
#
# Usage: from repo root or contracts/:  bash contracts/script/export-abis.sh
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"   # contracts/
OUT="$HERE/out"
DEST="$HERE/../packages/shared/src/abis"

# Contracts to export: only SparkPoint-OWNED, currently-implemented contracts.
# (The ERC-4337 account/factory/validator/policy ABIs are added by W6-US2; third-party
# ABIs — Aave Pool, Aerodrome, ERC-20/4626 — are sourced from viem/their own packages at
# the call site, never re-declared here.)
#   "<SolFile>:<Contract>:<exportCamelName>"
CONTRACTS=(
  "SparkPointVault:SparkPointVault:sparkPointVault"
  "CapRegistry:CapRegistry:capRegistry"
  "KillSwitch:KillSwitch:killSwitch"
  "AaveV3Adapter:AaveV3Adapter:aaveV3Adapter"
  "SparkPointAccount:SparkPointAccount:sparkPointAccount"
  "AccountFactory:AccountFactory:accountFactory"
  "SessionKeyValidator:SessionKeyValidator:sessionKeyValidator"
  "PolicyModule:PolicyModule:policyModule"
)

if [ ! -d "$OUT" ]; then
  echo "error: $OUT not found — run \`forge build\` first." >&2
  exit 1
fi

mkdir -p "$DEST"
names=()

for entry in "${CONTRACTS[@]}"; do
  sol="${entry%%:*}"; rest="${entry#*:}"; contract="${rest%%:*}"; camel="${rest#*:}"
  artifact="$OUT/$sol.sol/$contract.json"
  if [ ! -f "$artifact" ]; then
    echo "error: artifact $artifact missing — is \`forge build\` current?" >&2
    exit 1
  fi
  abi="$(jq -S '.abi' "$artifact")"
  file="$DEST/$camel.ts"
  {
    echo "// AUTO-GENERATED by contracts/script/export-abis.sh (T015) — DO NOT EDIT."
    echo "// Source: contracts/out/$sol.sol/$contract.json. Re-run the script to refresh."
    echo "/** ABI of the \`$contract\` contract (smart-contracts.md §1). */"
    echo "export const ${camel}Abi = $abi as const;"
  } > "$file"
  names+=("$camel")
  echo "  exported ${camel}Abi -> packages/shared/src/abis/$camel.ts"
done

# Vendored JSON artifact for the Python agent (services/agent chain/vault_reader.py):
# it needs the vault's `abi` AND `methodIdentifiers` (selectors, to stay keccak-free),
# so emit the compiled artifact's two fields as a committed, forge-build-free ABI the
# agent loads via SPARKPOINT_VAULT_ABI_PATH — no `contracts/out` at agent runtime/CI.
vault_artifact="$OUT/SparkPointVault.sol/SparkPointVault.json"
jq -S '{abi: .abi, methodIdentifiers: .methodIdentifiers}' "$vault_artifact" > "$DEST/SparkPointVault.abi.json"
echo "  exported SparkPointVault.abi.json (abi + methodIdentifiers) -> packages/shared/src/abis/"

# Barrel.
index="$DEST/index.ts"
{
  echo "// AUTO-GENERATED by contracts/script/export-abis.sh (T015) — DO NOT EDIT."
  echo "/**"
  echo " * Exported contract ABIs (single source of truth for the frontend + any TS"
  echo " * consumer). Addresses live in ../addresses (R14); this barrel is ABIs only."
  echo " */"
  for n in "${names[@]}"; do
    echo "export { ${n}Abi } from \"./$n\";"
  done
} > "$index"
echo "  wrote barrel -> packages/shared/src/abis/index.ts"
echo "done."
